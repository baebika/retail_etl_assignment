
-- CSV file format and internal Snowflake stage.

USE DATABASE RETAIL_DW;

CREATE FILE FORMAT IF NOT EXISTS BRONZE.FF_RETAIL_CSV
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    TRIM_SPACE = TRUE
    ENCODING = 'UTF8'
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE STAGE IF NOT EXISTS BRONZE.STG_RETAIL_INTERNAL
    FILE_FORMAT = BRONZE.FF_RETAIL_CSV
    DIRECTORY = (ENABLE = TRUE);
