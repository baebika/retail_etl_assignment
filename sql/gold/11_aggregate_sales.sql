
-- AGG: AGG_SLS_ITEM_LOCN_DAY

MERGE INTO RETAIL_DW.AGG.AGG_SLS_ITEM_LOCN_DAY t

USING (
    SELECT
        ITEM_KY,
        LOCATION_KY,
        DAY_KY,
        SUM(QUANTITY_SOLD) AS TOTAL_QTY_SOLD,
        SUM(DISCOUNT_AMT) AS TOTAL_DISCOUNT_AMT,
        SUM(TOTAL_SALES_AMT) AS TOTAL_SALES_AMT,
        COUNT(*) AS SLS_LINE_COUNT
    FROM RETAIL_DW.GOLD.FCT_SALES
    WHERE DAY_KY IN (
        SELECT DAY_KY
        FROM RETAIL_DW.GOLD.DIM_DAY
        WHERE FULL_DATE = TO_DATE('{BUSINESS_DATE}')
    )
    GROUP BY ITEM_KY, LOCATION_KY, DAY_KY
) s

ON t.ITEM_KY = s.ITEM_KY
AND t.LOCATION_KY = s.LOCATION_KY
AND t.DAY_KY = s.DAY_KY

WHEN MATCHED THEN UPDATE SET
    t.TOTAL_QTY_SOLD = s.TOTAL_QTY_SOLD,
    t.TOTAL_DISCOUNT_AMT = s.TOTAL_DISCOUNT_AMT,
    t.TOTAL_SALES_AMT = s.TOTAL_SALES_AMT,
    t.SLS_LINE_COUNT = s.SLS_LINE_COUNT,
    t.REC_UPDT_TS = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    ITEM_KY,
    LOCATION_KY,
    DAY_KY,
    TOTAL_QTY_SOLD,
    TOTAL_DISCOUNT_AMT,
    TOTAL_SALES_AMT,
    SLS_LINE_COUNT,
    REC_INS_TS
)
VALUES (
    s.ITEM_KY,
    s.LOCATION_KY,
    s.DAY_KY,
    s.TOTAL_QTY_SOLD,
    s.TOTAL_DISCOUNT_AMT,
    s.TOTAL_SALES_AMT,
    s.SLS_LINE_COUNT,
    CURRENT_TIMESTAMP()
);
