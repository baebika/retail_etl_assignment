
-- GOLD: DIM_LOCATION
-- LOCATION_NAME / CITY / DISTRICT_KY changes = SCD Type 2

-- Step 1: Close current versions when tracked attributes change
UPDATE RETAIL_DW.GOLD.DIM_LOCATION t
SET
    CURR_FLG = FALSE,
    EFF_TO_DT = DATEADD(
        DAY, -1, TO_DATE('{BUSINESS_DATE}')
    ),
    REC_UPDT_TS = CURRENT_TIMESTAMP(),
    BATCH_ID = {BATCH_ID}
FROM (
    SELECT
        l.LOCATION_ID,
        l.LOCATION_NAME,
        l.CITY,
        d.DISTRICT_KY
    FROM RETAIL_DW.SILVER.TMP_LOCATION l
    JOIN RETAIL_DW.GOLD.DIM_DISTRICT d
        ON l.DISTRICT_ID = d.DISTRICT_ID
    WHERE l.DROP_DATE = TO_DATE('{BUSINESS_DATE}')
      AND l.BATCH_ID = {BATCH_ID}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY l.LOCATION_ID
        ORDER BY l.REC_INS_TS DESC
    ) = 1
) s
WHERE t.LOCATION_ID = s.LOCATION_ID
  AND t.CURR_FLG = TRUE
  AND (
      COALESCE(t.LOCATION_NAME, '') <>
          COALESCE(s.LOCATION_NAME, '')
      OR COALESCE(t.CITY, '') <>
          COALESCE(s.CITY, '')
      OR t.DISTRICT_KY <> s.DISTRICT_KY
  );

-- Step 2: Insert only new locations or new SCD2 versions
INSERT INTO RETAIL_DW.GOLD.DIM_LOCATION (
    LOCATION_KY,
    LOCATION_ID,
    LOCATION_NAME,
    CITY,
    DISTRICT_KY,
    CURR_FLG,
    EFF_FROM_DT,
    EFF_TO_DT,
    REC_INS_TS,
    SRC_SYS_CD,
    BATCH_ID
)
SELECT
    RETAIL_DW.GOLD.SEQ_LOCATION_KY.NEXTVAL,
    s.LOCATION_ID,
    s.LOCATION_NAME,
    s.CITY,
    d.DISTRICT_KY,
    TRUE,
    s.DROP_DATE,
    TO_DATE('9999-12-31'),
    CURRENT_TIMESTAMP(),
    NULL,
    s.BATCH_ID
FROM (
    SELECT *
    FROM RETAIL_DW.SILVER.TMP_LOCATION
    WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
      AND BATCH_ID = {BATCH_ID}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY LOCATION_ID
        ORDER BY REC_INS_TS DESC
    ) = 1
) s
JOIN RETAIL_DW.GOLD.DIM_DISTRICT d
    ON s.DISTRICT_ID = d.DISTRICT_ID
WHERE NOT EXISTS (
    SELECT 1
    FROM RETAIL_DW.GOLD.DIM_LOCATION existing
    WHERE existing.LOCATION_ID = s.LOCATION_ID
      AND existing.CURR_FLG = TRUE
);
