
-- GOLD: FCT_SALES
-- Grain: One row per transaction line

MERGE INTO RETAIL_DW.GOLD.FCT_SALES t
USING (
    SELECT
        s.TXN_ID,
        s.TXN_LINE_NO,
        i.ITEM_KY,
        l.LOCATION_KY,
        d.DAY_KY,
        s.QUANTITY_SOLD,
        s.UNIT_SELLING_PRICE,
        s.DISCOUNT_AMT,
        s.TOTAL_SALES_AMT,
        s.BATCH_ID
    FROM RETAIL_DW.SILVER.TMP_SALES_LINE s

    JOIN RETAIL_DW.GOLD.DIM_ITEM i
        ON s.ITEM_ID = i.ITEM_ID
       AND s.SALES_DATE BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT

    JOIN RETAIL_DW.GOLD.DIM_LOCATION l
        ON s.LOCATION_ID = l.LOCATION_ID
       AND s.SALES_DATE BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT

    JOIN RETAIL_DW.GOLD.DIM_DAY d
        ON s.SALES_DATE = d.FULL_DATE

    WHERE s.DROP_DATE = TO_DATE('{BUSINESS_DATE}')
      AND s.BATCH_ID = {BATCH_ID}

    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY s.TXN_ID, s.TXN_LINE_NO
        ORDER BY s.REC_INS_TS DESC
    ) = 1

) s

ON t.TXN_ID = s.TXN_ID
AND t.TXN_LINE_NO = s.TXN_LINE_NO

WHEN NOT MATCHED THEN INSERT (
    SALES_ID,
    TXN_ID,
    TXN_LINE_NO,
    ITEM_KY,
    LOCATION_KY,
    CUSTOMER_KY,
    DAY_KY,
    QUANTITY_SOLD,
    UNIT_SELLING_PRICE,
    DISCOUNT_AMT,
    TOTAL_SALES_AMT,
    REC_INS_TS,
    SRC_SYS_CD,
    BATCH_ID
)
VALUES (
    RETAIL_DW.GOLD.SEQ_SALES_ID.NEXTVAL,
    s.TXN_ID,
    s.TXN_LINE_NO,
    s.ITEM_KY,
    s.LOCATION_KY,
    NULL,
    s.DAY_KY,
    s.QUANTITY_SOLD,
    s.UNIT_SELLING_PRICE,
    s.DISCOUNT_AMT,
    s.TOTAL_SALES_AMT,
    CURRENT_TIMESTAMP(),
    NULL,
    s.BATCH_ID
);
