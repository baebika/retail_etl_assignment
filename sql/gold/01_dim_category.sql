
-- GOLD: DIM_CATEGORY
-- SCD Type 1

MERGE INTO RETAIL_DW.GOLD.DIM_CATEGORY AS target
USING (
    SELECT
        CATEGORY_ID,
        CATEGORY_NAME,
        DROP_DATE,
        BATCH_ID
    FROM RETAIL_DW.SILVER.TMP_CATEGORY
    WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
      AND BATCH_ID = {BATCH_ID}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CATEGORY_ID
        ORDER BY REC_INS_TS DESC
    ) = 1
) AS source
ON target.CATEGORY_ID = source.CATEGORY_ID

WHEN MATCHED
 AND (
     COALESCE(target.CATEGORY_NAME, '') <>
     COALESCE(source.CATEGORY_NAME, '')
 )
THEN UPDATE SET
    target.CATEGORY_NAME = source.CATEGORY_NAME,
    target.REC_UPDT_TS = CURRENT_TIMESTAMP(),
    target.BATCH_ID = source.BATCH_ID

WHEN NOT MATCHED THEN INSERT (
    CATEGORY_KY,
    CATEGORY_ID,
    CATEGORY_NAME,
    CURR_FLG,
    EFF_FROM_DT,
    EFF_TO_DT,
    REC_INS_TS,
    SRC_SYS_CD,
    BATCH_ID
)
VALUES (
    RETAIL_DW.GOLD.SEQ_CATEGORY_KY.NEXTVAL,
    source.CATEGORY_ID,
    source.CATEGORY_NAME,
    TRUE,
    source.DROP_DATE,
    TO_DATE('9999-12-31'),
    CURRENT_TIMESTAMP(),
    NULL,
    source.BATCH_ID
);
