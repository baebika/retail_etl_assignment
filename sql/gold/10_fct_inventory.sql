
-- GOLD: FCT_INVENTORY
-- Positional loading
-- Grain: One row per item-location position over an effective period

-- STEP 1: Close previous positions

UPDATE RETAIL_DW.GOLD.FCT_INVENTORY t

SET
    CURR_FLG = FALSE,
    EFF_TO_DT = DATEADD(DAY, -1, s.SNAPSHOT_DATE),
    REC_UPDT_TS = CURRENT_TIMESTAMP(),
    BATCH_ID = s.BATCH_ID

FROM (
    SELECT
        s.ITEM_ID,
        s.LOCATION_ID,
        s.SNAPSHOT_DATE,
        s.BATCH_ID
    FROM RETAIL_DW.SILVER.TMP_INVENTORY_SNAPSHOT s
    WHERE s.DROP_DATE = TO_DATE('{BUSINESS_DATE}')
      AND s.BATCH_ID = {BATCH_ID}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY s.ITEM_ID, s.LOCATION_ID
        ORDER BY s.REC_INS_TS DESC
    ) = 1
) s,
RETAIL_DW.GOLD.DIM_ITEM old_i,
RETAIL_DW.GOLD.DIM_LOCATION old_l

WHERE old_i.ITEM_KY = t.ITEM_KY
  AND old_l.LOCATION_KY = t.LOCATION_KY
  AND old_i.ITEM_ID = s.ITEM_ID
  AND old_l.LOCATION_ID = s.LOCATION_ID
  AND t.CURR_FLG = TRUE
  AND t.EFF_FROM_DT < s.SNAPSHOT_DATE;


-- STEP 2: Update existing same-date positions
-- Makes same-date reruns idempotent

MERGE INTO RETAIL_DW.GOLD.FCT_INVENTORY t
USING (
    SELECT
        src.ITEM_ID,
        src.LOCATION_ID,
        src.SNAPSHOT_DATE,
        src.QUANTITY_ON_HAND,
        i.ITEM_KY,
        l.LOCATION_KY,
        d.DAY_KY,
        src.BATCH_ID
    FROM RETAIL_DW.SILVER.TMP_INVENTORY_SNAPSHOT src
    JOIN RETAIL_DW.GOLD.DIM_ITEM i
        ON src.ITEM_ID = i.ITEM_ID
       AND src.SNAPSHOT_DATE BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
    JOIN RETAIL_DW.GOLD.DIM_LOCATION l
        ON src.LOCATION_ID = l.LOCATION_ID
       AND src.SNAPSHOT_DATE BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
    JOIN RETAIL_DW.GOLD.DIM_DAY d
        ON src.SNAPSHOT_DATE = d.FULL_DATE
    WHERE src.DROP_DATE = TO_DATE('{BUSINESS_DATE}')
      AND src.BATCH_ID = {BATCH_ID}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY src.ITEM_ID, src.LOCATION_ID
        ORDER BY src.REC_INS_TS DESC
    ) = 1
) s
ON t.EFF_FROM_DT = s.SNAPSHOT_DATE
AND EXISTS (
    SELECT 1
    FROM RETAIL_DW.GOLD.DIM_ITEM old_i
    WHERE old_i.ITEM_KY = t.ITEM_KY
      AND old_i.ITEM_ID = s.ITEM_ID
)
AND EXISTS (
    SELECT 1
    FROM RETAIL_DW.GOLD.DIM_LOCATION old_l
    WHERE old_l.LOCATION_KY = t.LOCATION_KY
      AND old_l.LOCATION_ID = s.LOCATION_ID
)

WHEN MATCHED THEN UPDATE SET
    t.QUANTITY_ON_HAND = s.QUANTITY_ON_HAND,
    t.ITEM_KY = s.ITEM_KY,
    t.LOCATION_KY = s.LOCATION_KY,
    t.DAY_KY = s.DAY_KY,
    t.REC_UPDT_TS = CURRENT_TIMESTAMP(),
    t.BATCH_ID = s.BATCH_ID;

-- STEP 3: Insert new positions

INSERT INTO RETAIL_DW.GOLD.FCT_INVENTORY (
    ITEM_KY,
    LOCATION_KY,
    DAY_KY,
    QUANTITY_ON_HAND,
    EFF_FROM_DT,
    EFF_TO_DT,
    CURR_FLG,
    REC_INS_TS,
    SRC_SYS_CD,
    BATCH_ID
)

SELECT
    s.ITEM_KY,
    s.LOCATION_KY,
    s.DAY_KY,
    s.QUANTITY_ON_HAND,
    s.SNAPSHOT_DATE,
    TO_DATE('9999-12-31'),
    TRUE,
    CURRENT_TIMESTAMP(),
    NULL,
    s.BATCH_ID

FROM (
    SELECT
        src.ITEM_ID,
        src.LOCATION_ID,
        src.SNAPSHOT_DATE,
        src.QUANTITY_ON_HAND,
        i.ITEM_KY,
        l.LOCATION_KY,
        d.DAY_KY,
        src.BATCH_ID
    FROM RETAIL_DW.SILVER.TMP_INVENTORY_SNAPSHOT src
    JOIN RETAIL_DW.GOLD.DIM_ITEM i
        ON src.ITEM_ID = i.ITEM_ID
       AND src.SNAPSHOT_DATE BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
    JOIN RETAIL_DW.GOLD.DIM_LOCATION l
        ON src.LOCATION_ID = l.LOCATION_ID
       AND src.SNAPSHOT_DATE BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
    JOIN RETAIL_DW.GOLD.DIM_DAY d
        ON src.SNAPSHOT_DATE = d.FULL_DATE
    WHERE src.DROP_DATE = TO_DATE('{BUSINESS_DATE}')
      AND src.BATCH_ID = {BATCH_ID}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY src.ITEM_ID, src.LOCATION_ID
        ORDER BY src.REC_INS_TS DESC
    ) = 1
) s

WHERE NOT EXISTS (
    SELECT 1
    FROM RETAIL_DW.GOLD.FCT_INVENTORY existing
    JOIN RETAIL_DW.GOLD.DIM_ITEM ei
        ON existing.ITEM_KY = ei.ITEM_KY
    JOIN RETAIL_DW.GOLD.DIM_LOCATION el
        ON existing.LOCATION_KY = el.LOCATION_KY
    WHERE ei.ITEM_ID = s.ITEM_ID
      AND el.LOCATION_ID = s.LOCATION_ID
      AND existing.EFF_FROM_DT = s.SNAPSHOT_DATE
);
