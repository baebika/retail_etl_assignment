
-- GOLD: DIM_DISTRICT
-- SCD Type 1

MERGE INTO RETAIL_DW.GOLD.DIM_DISTRICT AS target
USING (
    SELECT
        DISTRICT_ID,
        DISTRICT_NAME,
        PROVINCE,
        DROP_DATE,
        BATCH_ID
    FROM RETAIL_DW.SILVER.TMP_DISTRICT
    WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
      AND BATCH_ID = {BATCH_ID}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY DISTRICT_ID
        ORDER BY REC_INS_TS DESC
    ) = 1
) AS source
ON target.DISTRICT_ID = source.DISTRICT_ID

WHEN MATCHED
 AND (
     COALESCE(target.DISTRICT_NAME, '') <>
     COALESCE(source.DISTRICT_NAME, '')
     OR COALESCE(target.PROVINCE, '') <>
        COALESCE(source.PROVINCE, '')
 )
THEN UPDATE SET
    target.DISTRICT_NAME = source.DISTRICT_NAME,
    target.PROVINCE = source.PROVINCE,
    target.REC_UPDT_TS = CURRENT_TIMESTAMP(),
    target.BATCH_ID = source.BATCH_ID

WHEN NOT MATCHED THEN INSERT (
    DISTRICT_KY,
    DISTRICT_ID,
    DISTRICT_NAME,
    PROVINCE,
    CURR_FLG,
    EFF_FROM_DT,
    EFF_TO_DT,
    REC_INS_TS,
    SRC_SYS_CD,
    BATCH_ID
)
VALUES (
    RETAIL_DW.GOLD.SEQ_DISTRICT_KY.NEXTVAL,
    source.DISTRICT_ID,
    source.DISTRICT_NAME,
    source.PROVINCE,
    TRUE,
    source.DROP_DATE,
    TO_DATE('9999-12-31'),
    CURRENT_TIMESTAMP(),
    NULL,
    source.BATCH_ID
);
