
-- =====================================================
-- GOLD LAYER: TABLE DEFINITIONS
-- Database: RETAIL_DW
-- =====================================================

CREATE SCHEMA IF NOT EXISTS RETAIL_DW.GOLD;
CREATE SCHEMA IF NOT EXISTS RETAIL_DW.AGG;

-- -----------------------------------------------------
-- SURROGATE KEY SEQUENCES
-- -----------------------------------------------------

CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_CATEGORY_KY;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_DISTRICT_KY;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_DAY_KY;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_MONTH_KY;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_QUARTER_KY;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_ITEM_KY;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_LOCATION_KY;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_CUSTOMER_KY;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_SALES_ID;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_INVENTORY_ID;
CREATE SEQUENCE IF NOT EXISTS RETAIL_DW.GOLD.SEQ_PRICE_ID;

-- -----------------------------------------------------
-- DIM_CATEGORY
-- SCD Type 1
-- -----------------------------------------------------

CREATE TABLE IF NOT EXISTS RETAIL_DW.GOLD.DIM_CATEGORY (
    CATEGORY_KY NUMBER(38,0) NOT NULL
        DEFAULT RETAIL_DW.GOLD.SEQ_CATEGORY_KY.NEXTVAL,
    CATEGORY_ID VARCHAR(100) NOT NULL,
    CATEGORY_NAME VARCHAR(255),
    CURR_FLG BOOLEAN,
    EFF_FROM_DT DATE,
    EFF_TO_DT DATE,
    REC_INS_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    REC_UPDT_TS TIMESTAMP_NTZ,
    SRC_SYS_CD NUMBER(38,0),
    BATCH_ID NUMBER(38,0),
    PRIMARY KEY (CATEGORY_KY)
);

-- -----------------------------------------------------
-- DIM_DISTRICT
-- SCD Type 2
-- -----------------------------------------------------

CREATE TABLE IF NOT EXISTS RETAIL_DW.GOLD.DIM_DISTRICT (
    DISTRICT_KY NUMBER(38,0) NOT NULL
        DEFAULT RETAIL_DW.GOLD.SEQ_DISTRICT_KY.NEXTVAL,
    DISTRICT_ID VARCHAR(100) NOT NULL,
    DISTRICT_NAME VARCHAR(255),
    PROVINCE VARCHAR(255),
    CURR_FLG BOOLEAN,
    EFF_FROM_DT DATE,
    EFF_TO_DT DATE,
    REC_INS_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    REC_UPDT_TS TIMESTAMP_NTZ,
    SRC_SYS_CD NUMBER(38,0),
    BATCH_ID NUMBER(38,0),
    PRIMARY KEY (DISTRICT_KY)
);

-- -----------------------------------------------------
-- DIM_QUARTER
-- -----------------------------------------------------

CREATE TABLE IF NOT EXISTS RETAIL_DW.GOLD.DIM_QUARTER (
    QUARTER_KY NUMBER(38,0) NOT NULL
        DEFAULT RETAIL_DW.GOLD.SEQ_QUARTER_KY.NEXTVAL,
    QUARTER_NAME VARCHAR(100),
    "YEAR" NUMBER(4,0),
    PRIMARY KEY (QUARTER_KY)
);

-- -----------------------------------------------------
-- DIM_MONTH
-- -----------------------------------------------------

CREATE TABLE IF NOT EXISTS RETAIL_DW.GOLD.DIM_MONTH (
    MONTH_KY NUMBER(38,0) NOT NULL
        DEFAULT RETAIL_DW.GOLD.SEQ_MONTH_KY.NEXTVAL,
    MONTH_NAME VARCHAR(100),
    QUARTER_KY NUMBER(38,0),
    PRIMARY KEY (MONTH_KY),
    FOREIGN KEY (QUARTER_KY)
        REFERENCES RETAIL_DW.GOLD.DIM_QUARTER(QUARTER_KY)
);

-- -----------------------------------------------------
-- DIM_DAY
-- -----------------------------------------------------

CREATE TABLE IF NOT EXISTS RETAIL_DW.GOLD.DIM_DAY (
    DAY_KY NUMBER(38,0) NOT NULL
        DEFAULT RETAIL_DW.GOLD.SEQ_DAY_KY.NEXTVAL,
    FULL_DATE DATE NOT NULL,
    "DAY" NUMBER(2,0),
    DAY_NAME VARCHAR(50),
    MONTH_KY NUMBER(38,0),
    IS_WEEKEND BOOLEAN,
    REC_INS_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    REC_UPDT_TS TIMESTAMP_NTZ,
    PRIMARY KEY (DAY_KY),
    FOREIGN KEY (MONTH_KY)
        REFERENCES RETAIL_DW.GOLD.DIM_MONTH(MONTH_KY)
);

-- -----------------------------------------------------
-- DIM_ITEM
-- SCD Type 2
-- -----------------------------------------------------

CREATE TABLE IF NOT EXISTS RETAIL_DW.GOLD.DIM_ITEM (
    ITEM_KY NUMBER(38,0) NOT NULL
        DEFAULT RETAIL_DW.GOLD.SEQ_ITEM_KY.NEXTVAL,
    ITEM_ID VARCHAR(100) NOT NULL,
    ITEM_NAME VARCHAR(255),
    BRAND VARCHAR(255),
    CATEGORY_KY NUMBER(38,0),
    CURR_FLG BOOLEAN,
    EFF_FROM_DT DATE,
    EFF_TO_DT DATE,
    REC_INS_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    REC_UPDT_TS TIMESTAMP_NTZ,
    SRC_SYS_CD NUMBER(38,0),
    BATCH_ID NUMBER(38,0),
    PRIMARY KEY (ITEM_KY),
    FOREIGN KEY (CATEGORY_KY)
        REFERENCES RETAIL_DW.GOLD.DIM_CATEGORY(CATEGORY_KY)
);

