-- -----------------------------------------------------
-- DIM_CUSTOMER
-- -----------------------------------------------------

CREATE TABLE IF NOT EXISTS RETAIL_DW.GOLD.DIM_CUSTOMER (
    CUSTOMER_KY NUMBER(38,0) NOT NULL
        DEFAULT RETAIL_DW.GOLD.SEQ_CUSTOMER_KY.NEXTVAL,
    CUSTOMER_ID VARCHAR(100),
    CUSTOMER_NAME VARCHAR(255),
