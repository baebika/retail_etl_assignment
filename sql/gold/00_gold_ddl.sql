    DAY_KY NUMBER(38,0) NOT NULL,
    TOTAL_QTY_SOLD NUMBER(18,3),
    TOTAL_DISCOUNT_AMT NUMBER(18,2),
    TOTAL_SALES_AMT NUMBER(18,2),
    SLS_LINE_COUNT NUMBER(38,0),
    REC_INS_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
