-- -----------------------------------------------------
-- AGGREGATE MART
-- -----------------------------------------------------

CREATE TABLE IF NOT EXISTS RETAIL_DW.AGG.AGG_SLS_ITEM_LOCN_DAY (
    ITEM_KY NUMBER(38,0) NOT NULL,
