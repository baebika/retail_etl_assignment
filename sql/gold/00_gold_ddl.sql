-- -----------------------------------------------------
-- FCT_SALES
-- -----------------------------------------------------

CREATE TABLE IF NOT EXISTS RETAIL_DW.GOLD.FCT_SALES (
    SALES_ID NUMBER(38,0) NOT NULL
        DEFAULT RETAIL_DW.GOLD.SEQ_SALES_ID.NEXTVAL,
    ITEM_KY NUMBER(38,0),
    LOCATION_KY NUMBER(38,0),
    CUSTOMER_KY NUMBER(38,0),
    DAY_KY NUMBER(38,0),
    QUANTITY_SOLD NUMBER(18,3),
    UNIT_SELLING_PRICE NUMBER(18,2),
    DISCOUNT_AMT NUMBER(18,2),
    TOTAL_SALES_AMT NUMBER(18,2),
    REC_INS_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    REC_UPDT_TS TIMESTAMP_NTZ,
    SRC_SYS_CD NUMBER(38,0),
    BATCH_ID NUMBER(38,0),
    PRIMARY KEY (SALES_ID),
    FOREIGN KEY (ITEM_KY)
        REFERENCES RETAIL_DW.GOLD.DIM_ITEM(ITEM_KY),
    FOREIGN KEY (LOCATION_KY)
        REFERENCES RETAIL_DW.GOLD.DIM_LOCATION(LOCATION_KY),
    FOREIGN KEY (CUSTOMER_KY)
        REFERENCES RETAIL_DW.GOLD.DIM_CUSTOMER(CUSTOMER_KY),
    FOREIGN KEY (DAY_KY)
        REFERENCES RETAIL_DW.GOLD.DIM_DAY(DAY_KY)
);

-- -----------------------------------------------------
-- FCT_INVENTORY
-- -----------------------------------------------------

