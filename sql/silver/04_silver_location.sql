DELETE FROM RETAIL_DW.SILVER.TMP_LOCATION
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}');

INSERT INTO RETAIL_DW.SILVER.TMP_LOCATION (
    LOCATION_ID, LOCATION_NAME, CITY, DISTRICT_ID,
    DROP_DATE, SRC_FILE_NAME, SRC_ROW_NUM,
    BATCH_ID, REC_INS_TS
)
SELECT
    TRIM(STORE_ID),
    NULLIF(TRIM(STORE_NAME), ''),
    NULLIF(TRIM(CITY), ''),
    TRIM(DISTRICT_ID),
    TO_DATE('{BUSINESS_DATE}'),
    SRC_FILE_NAME,
    SRC_ROW_NUM,
    {BATCH_ID},
    CURRENT_TIMESTAMP()
FROM RETAIL_DW.BRONZE.STG_STORE_MASTER
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
  AND NULLIF(TRIM(STORE_ID), '') IS NOT NULL
  AND NULLIF(TRIM(DISTRICT_ID), '') IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY TRIM(STORE_ID)
    ORDER BY SRC_ROW_NUM DESC
) = 1;