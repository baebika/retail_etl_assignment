DELETE FROM RETAIL_DW.SILVER.TMP_INVENTORY_SNAPSHOT
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}');

INSERT INTO RETAIL_DW.SILVER.TMP_INVENTORY_SNAPSHOT (
    SNAPSHOT_DATE, LOCATION_ID, ITEM_ID,
    QUANTITY_ON_HAND, DROP_DATE, SRC_FILE_NAME,
    SRC_ROW_NUM, BATCH_ID, REC_INS_TS
)
SELECT
    TRY_TO_DATE(SNAPSHOT_DATE),
    TRIM(STORE_ID),
    TRIM(ITEM_ID),
    TRY_TO_NUMBER(QTY_ON_HAND),
    TO_DATE('{BUSINESS_DATE}'),
    SRC_FILE_NAME,
    SRC_ROW_NUM,
    {BATCH_ID},
    CURRENT_TIMESTAMP()
FROM RETAIL_DW.BRONZE.STG_INVENTORY_SNAPSHOT
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
  AND TRY_TO_DATE(SNAPSHOT_DATE) IS NOT NULL
  AND NULLIF(TRIM(STORE_ID), '') IS NOT NULL
  AND NULLIF(TRIM(ITEM_ID), '') IS NOT NULL
  AND TRY_TO_NUMBER(QTY_ON_HAND) IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY SNAPSHOT_DATE, STORE_ID, ITEM_ID
    ORDER BY SRC_ROW_NUM DESC
) = 1;