DELETE FROM RETAIL_DW.SILVER.TMP_QUARANTINE_ROW
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
AND SOURCE_NAME = 'POS_SALES';

INSERT INTO RETAIL_DW.SILVER.TMP_QUARANTINE_ROW (
    QUARANTINE_ID, DROP_DATE, SOURCE_NAME, GATE_CODE,
    REASON_CODE, REASON_DESC, SRC_FILE_NAME,
    SRC_ROW_NUM, RAW_ROW, BATCH_ID, REC_INS_TS
)
WITH SALES AS (
    SELECT *,
        ROW_NUMBER() OVER (
            PARTITION BY TXN_ID, TRY_TO_NUMBER(LINE_NO)
            ORDER BY SRC_ROW_NUM
        ) AS DUP_RN
    FROM RETAIL_DW.BRONZE.STG_POS_SALES
    WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
)
SELECT
    RETAIL_DW.SILVER.SEQ_QUARANTINE_ID.NEXTVAL,
    TO_DATE('{BUSINESS_DATE}'),
    'POS_SALES',
    'SILVER',
    CASE
        WHEN NULLIF(TRIM(ITEM_ID), '') IS NULL THEN 'NULL_ITEM_ID'
        WHEN TRY_TO_NUMBER(QUANTITY) < 0 THEN 'NEGATIVE_QUANTITY'
        WHEN TRY_TO_NUMBER(QUANTITY) IS NULL THEN 'INVALID_QUANTITY'
        WHEN TRY_TO_NUMBER(LINE_NO) IS NULL THEN 'INVALID_LINE_NUMBER'
        WHEN DUP_RN > 1 THEN 'DUPLICATE_TRANSACTION_LINE'
        WHEN NOT EXISTS (
            SELECT 1
            FROM RETAIL_DW.BRONZE.STG_ITEM_MASTER I
            WHERE I.DROP_DATE = TO_DATE('{BUSINESS_DATE}')
              AND I.ITEM_ID = SALES.ITEM_ID
        ) THEN 'ITEM_NOT_IN_MASTER'
    END,
    CASE
        WHEN NULLIF(TRIM(ITEM_ID), '') IS NULL THEN 'Item ID is missing'
        WHEN TRY_TO_NUMBER(QUANTITY) < 0 THEN 'Sales quantity is negative'
        WHEN TRY_TO_NUMBER(QUANTITY) IS NULL THEN 'Sales quantity is invalid'
        WHEN TRY_TO_NUMBER(LINE_NO) IS NULL THEN 'Transaction line number is invalid'
        WHEN DUP_RN > 1 THEN 'Duplicate transaction line'
        ELSE 'Item does not exist in item master'
    END,
    SRC_FILE_NAME,
    SRC_ROW_NUM,
    OBJECT_CONSTRUCT_KEEP_NULL(
        'TXN_ID', TXN_ID,
        'LINE_NO', LINE_NO,
        'TXN_TS', TXN_TS,
        'STORE_ID', STORE_ID,
        'ITEM_ID', ITEM_ID,
        'QUANTITY', QUANTITY,
        'UNIT_PRICE', UNIT_PRICE,
        'DISCOUNT_AMT', DISCOUNT_AMT
    ),
    {BATCH_ID},
    CURRENT_TIMESTAMP()
FROM SALES
WHERE
    NULLIF(TRIM(ITEM_ID), '') IS NULL
    OR TRY_TO_NUMBER(QUANTITY) < 0
    OR TRY_TO_NUMBER(QUANTITY) IS NULL
    OR TRY_TO_NUMBER(LINE_NO) IS NULL
    OR DUP_RN > 1
    OR NOT EXISTS (
        SELECT 1
        FROM RETAIL_DW.BRONZE.STG_ITEM_MASTER I
        WHERE I.DROP_DATE = TO_DATE('{BUSINESS_DATE}')
          AND I.ITEM_ID = SALES.ITEM_ID
    );