DELETE FROM RETAIL_DW.SILVER.TMP_CATEGORY
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}');

INSERT INTO RETAIL_DW.SILVER.TMP_CATEGORY (
    CATEGORY_ID, CATEGORY_NAME, DROP_DATE, BATCH_ID, REC_INS_TS
)
SELECT
    CATEGORY_ID,
    MAX(CATEGORY_NAME),
    TO_DATE('{BUSINESS_DATE}'),
    {BATCH_ID},
    CURRENT_TIMESTAMP()
FROM RETAIL_DW.BRONZE.STG_ITEM_MASTER
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
  AND NULLIF(TRIM(CATEGORY_ID), '') IS NOT NULL
GROUP BY CATEGORY_ID;