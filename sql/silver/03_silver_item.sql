DELETE FROM RETAIL_DW.SILVER.TMP_ITEM
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}');

INSERT INTO RETAIL_DW.SILVER.TMP_ITEM (
    ITEM_ID, ITEM_NAME, BRAND, CATEGORY_ID,
    DROP_DATE, SRC_FILE_NAME, SRC_ROW_NUM,
    BATCH_ID, REC_INS_TS
)
SELECT
    TRIM(ITEM_ID),
    NULLIF(TRIM(ITEM_NAME), ''),
    NULLIF(TRIM(BRAND), ''),
    TRIM(CATEGORY_ID),
    TO_DATE('{BUSINESS_DATE}'),
    SRC_FILE_NAME,
    SRC_ROW_NUM,
    {BATCH_ID},
    CURRENT_TIMESTAMP()
FROM RETAIL_DW.BRONZE.STG_ITEM_MASTER
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
  AND NULLIF(TRIM(ITEM_ID), '') IS NOT NULL
  AND NULLIF(TRIM(CATEGORY_ID), '') IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY TRIM(ITEM_ID)
    ORDER BY SRC_ROW_NUM DESC
) = 1;