DELETE FROM RETAIL_DW.SILVER.TMP_DISTRICT
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}');

INSERT INTO RETAIL_DW.SILVER.TMP_DISTRICT (
    DISTRICT_ID, DISTRICT_NAME, PROVINCE,
    DROP_DATE, BATCH_ID, REC_INS_TS
)
SELECT
    DISTRICT_ID,
    MAX(DISTRICT_NAME),
    MAX(PROVINCE),
    TO_DATE('{BUSINESS_DATE}'),
    {BATCH_ID},
    CURRENT_TIMESTAMP()
FROM RETAIL_DW.BRONZE.STG_STORE_MASTER
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
  AND NULLIF(TRIM(DISTRICT_ID), '') IS NOT NULL
GROUP BY DISTRICT_ID;