DELETE FROM RETAIL_DW.SILVER.TMP_SALES_LINE
WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}');

INSERT INTO RETAIL_DW.SILVER.TMP_SALES_LINE (
    TXN_ID, TXN_LINE_NO, SALES_TS, SALES_DATE,
    LOCATION_ID, ITEM_ID, QUANTITY_SOLD,
    UNIT_SELLING_PRICE, DISCOUNT_AMT, TOTAL_SALES_AMT,
    DROP_DATE, SRC_FILE_NAME, SRC_ROW_NUM,
    BATCH_ID, REC_INS_TS
)
WITH CLEAN AS (
    SELECT
        S.*,
        TRY_TO_TIMESTAMP_NTZ(TXN_TS) AS CLEAN_TS,
        TRY_TO_NUMBER(LINE_NO) AS CLEAN_LINE,
        TRY_TO_NUMBER(QUANTITY) AS CLEAN_QTY,
        TRY_TO_DECIMAL(UNIT_PRICE, 18, 2) AS CLEAN_PRICE,
        TRY_TO_DECIMAL(DISCOUNT_AMT, 18, 2) AS CLEAN_DISCOUNT,
        ROW_NUMBER() OVER (
            PARTITION BY TXN_ID, TRY_TO_NUMBER(LINE_NO)
            ORDER BY SRC_ROW_NUM
        ) AS DUP_RN
    FROM RETAIL_DW.BRONZE.STG_POS_SALES S
    WHERE DROP_DATE = TO_DATE('{BUSINESS_DATE}')
)
SELECT
    TXN_ID,
    CLEAN_LINE,
    CLEAN_TS,
    TO_DATE(CLEAN_TS),
    TRIM(STORE_ID),
    TRIM(ITEM_ID),
    CLEAN_QTY,
    CLEAN_PRICE,
    CLEAN_DISCOUNT,
    (CLEAN_QTY * CLEAN_PRICE) - CLEAN_DISCOUNT,
    TO_DATE('{BUSINESS_DATE}'),
    SRC_FILE_NAME,
    SRC_ROW_NUM,
    {BATCH_ID},
    CURRENT_TIMESTAMP()
FROM CLEAN S
WHERE NULLIF(TRIM(ITEM_ID), '') IS NOT NULL
  AND CLEAN_QTY > 0
  AND CLEAN_LINE IS NOT NULL
  AND CLEAN_TS IS NOT NULL
  AND CLEAN_PRICE IS NOT NULL
  AND CLEAN_DISCOUNT IS NOT NULL
  AND DUP_RN = 1
  AND EXISTS (
      SELECT 1
      FROM RETAIL_DW.BRONZE.STG_ITEM_MASTER I
      WHERE I.DROP_DATE = TO_DATE('{BUSINESS_DATE}')
        AND I.ITEM_ID = S.ITEM_ID
  )
  AND EXISTS (
      SELECT 1
      FROM RETAIL_DW.BRONZE.STG_STORE_MASTER L
      WHERE L.DROP_DATE = TO_DATE('{BUSINESS_DATE}')
        AND L.STORE_ID = S.STORE_ID
  );